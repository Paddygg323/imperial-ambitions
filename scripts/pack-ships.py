"""Pack reviewed ship artwork for Canvas2D; never modifies the source PNGs.

Run from the repository root with Python + Pillow after changing the ship index.
Cropping uses the review's measured bounds including transparent safety margins.
"""
from pathlib import Path
from PIL import Image
import hashlib
import json

root = Path(__file__).resolve().parent.parent
source = root / 'outputs/sprite-library-review/revisions/ships-v2'
catalog = json.loads((source / 'catalog.json').read_text(encoding='utf-8'))
cell, padding, columns = 384, 16, 4
atlas = Image.new('RGBA', (cell * columns, cell * 3))
frames = {}
for index, unit in enumerate(catalog['units']):
    path = source / unit['file']
    assert hashlib.sha256(path.read_bytes()).hexdigest() == unit['sha256']
    original = Image.open(path).convert('RGBA')
    left, top, right, bottom = unit['crop']
    assert 0 <= left < right <= original.width and 0 <= top < bottom <= original.height
    image = original.crop((left, top, right, bottom))
    ratio = min((cell - 2 * padding) / image.width, (cell - 2 * padding) / image.height)
    size = tuple(round(n * ratio) for n in image.size)
    image = image.resize(size, Image.Resampling.LANCZOS)
    x = index % columns * cell + (cell - size[0]) // 2
    y = index // columns * cell + cell - padding - size[1]
    atlas.paste(image, (x, y))
    frames[unit['type']] = {
        'rect': [x, y, *size], 'source_size': list(original.size),
        'trim_offset': [left, top], 'trim_size': [right-left, bottom-top],
        'pivot': [(left+right)/2, bottom], 'rotation': False,
        'sockets': {}, 'duration_ms': 0, 'scale': unit['scale'],
        'source': path.relative_to(root).as_posix(), 'sha256': unit['sha256'],
    }
output = root / 'game/assets/naval'
output.mkdir(parents=True, exist_ok=True)
atlas.save(output / 'ships.png', optimize=True)
metadata = {
    'url': './assets/naval/ships.png', 'width': atlas.width, 'height': atlas.height,
    'packing': 'trimmed-pack; no rotation', 'padding': padding,
    'alpha': 'straight RGBA', 'axes': 'x right, y down; source pixels',
    'filtering': 'Canvas2D high-quality linear; no mipmaps',
    'rights': 'Original generated artwork; prompts and references in sprite library',
    'frames': frames,
}
(root / 'game/ship-atlas.mjs').write_text(
    '// Generated by scripts/pack-ships.py. Source artwork is retained in the review library.\n'
    'export const SHIP_ATLAS = ' + json.dumps(metadata, indent=2) + ';\n', encoding='utf-8')
print(json.dumps({'ships': len(frames), 'atlas': list(atlas.size), 'bytes': (output/'ships.png').stat().st_size}))
